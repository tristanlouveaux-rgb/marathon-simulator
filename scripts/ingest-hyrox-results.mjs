#!/usr/bin/env node
/**
 * Ingest the Kaggle HYROX results CSV into baked percentile tables for
 * `src/data/hyrox-population-distributions.ts`.
 *
 * Source: jgug05/hyrox-results (Kaggle, Seasons 4-6, ~92k rows).
 * Format columns: open / pro / doubles / relay / elite / goruck*. We bake the
 * first three into `open_singles`, `pro_singles`, `open_doubles` respectively.
 * `pro_doubles` has no rows in this dataset → leave its tables empty (predictor
 * falls back to synthesised distributions when a table is empty).
 *
 * Run:  node scripts/ingest-hyrox-results.mjs <path-to-csv> > out.txt
 *       then paste the printed const blocks into hyrox-population-distributions.ts.
 */
import fs from 'node:fs';

const CSV_PATH = process.argv[2];
if (!CSV_PATH) {
  console.error('Usage: node scripts/ingest-hyrox-results.mjs <path-to-csv>');
  process.exit(1);
}

/** "0:59:07" → 3547 seconds. Returns NaN on bad input. */
function timeToSec(s) {
  if (!s || typeof s !== 'string') return NaN;
  const parts = s.split(':').map(Number);
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  return NaN;
}

const FORMAT_MAP = {
  open:    'open_singles',
  pro:     'pro_singles',
  doubles: 'open_doubles',
};

// Percentile breakpoints we want in the baked table.
const BREAKS = [1, 5, 10, 25, 50, 75, 90, 95, 99];

/** sorted ascending → return the value at percentile p (0-100). */
function percentileAt(sortedAsc, p) {
  if (sortedAsc.length === 0) return null;
  const idx = Math.max(0, Math.min(sortedAsc.length - 1, Math.round((p / 100) * (sortedAsc.length - 1))));
  return sortedAsc[idx];
}

const raw = fs.readFileSync(CSV_PATH, 'utf-8');
const lines = raw.split('\n');
const header = lines[0].split(',');
const colIdx = (n) => header.indexOf(n);

const cTotal   = colIdx('total_time');
const cWork    = colIdx('work_time');
const cRoxzone = colIdx('roxzone_time');
const cRun     = colIdx('run_time');
const cDiv     = colIdx('division');

if ([cTotal, cWork, cRoxzone, cRun, cDiv].some(i => i < 0)) {
  console.error('CSV is missing one of: total_time, work_time, roxzone_time, run_time, division');
  process.exit(1);
}

// Bucket: { format → { total: [], run: [], work: [], roxzone: [] } }
const buckets = {};
for (const fmt of Object.values(FORMAT_MAP)) {
  buckets[fmt] = { total: [], run: [], work: [], roxzone: [] };
}

let parsed = 0, skipped = 0;
for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line.trim()) continue;
  const cols = line.split(',');
  const div = cols[cDiv];
  const fmt = FORMAT_MAP[div];
  if (!fmt) { skipped++; continue; }

  const total   = timeToSec(cols[cTotal]);
  const run     = timeToSec(cols[cRun]);
  const work    = timeToSec(cols[cWork]);
  const roxzone = timeToSec(cols[cRoxzone]);

  // Sanity-check: implausible values (DNS / scoring errors) get dropped.
  if (!Number.isFinite(total) || total < 1800 || total > 18000) { skipped++; continue; }
  if (!Number.isFinite(run) || run < 1200 || run > 9000) { skipped++; continue; }

  const b = buckets[fmt];
  b.total.push(total);
  b.run.push(run);
  if (Number.isFinite(work)) b.work.push(work);
  if (Number.isFinite(roxzone)) b.roxzone.push(roxzone);
  parsed++;
}

console.error(`Ingested: ${parsed} rows. Skipped: ${skipped}.`);
console.error('Per-format counts:');
for (const [fmt, b] of Object.entries(buckets)) {
  console.error(`  ${fmt}: total=${b.total.length} run=${b.run.length} work=${b.work.length} roxzone=${b.roxzone.length}`);
}

function buildTable(arr) {
  arr.sort((a, b) => a - b);
  return BREAKS.map(p => [percentileAt(arr, p), p]);
}

function fmtTable(buckets, key) {
  const rows = [];
  for (const fmt of ['open_singles', 'pro_singles', 'open_doubles', 'pro_doubles']) {
    const b = buckets[fmt];
    if (!b || b[key].length === 0) {
      rows.push(`  ${fmt}: [],`);
      continue;
    }
    const tbl = buildTable(b[key]);
    const tblStr = tbl.map(([t, p]) => `[${t}, ${p}]`).join(', ');
    rows.push(`  ${fmt}: [${tblStr}],`);
  }
  return rows.join('\n');
}

console.log('// ── Generated by scripts/ingest-hyrox-results.mjs ──────────────────────');
console.log(`// Source: jgug05/hyrox-results (Kaggle). Ingested ${parsed} rows.`);
console.log(`// Last refresh: ${new Date().toISOString().slice(0, 10)}.`);
console.log('');
console.log('export const HYROX_TOTAL_PERCENTILE_TABLES: Record<Format, Array<[number, number]>> = {');
console.log(fmtTable(buckets, 'total'));
console.log('};');
console.log('');
console.log('export const HYROX_RUN_PERCENTILE_TABLES: Record<Format, Array<[number, number]>> = {');
console.log(fmtTable(buckets, 'run'));
console.log('};');
console.log('');
console.log('export const HYROX_STATIONS_PERCENTILE_TABLES: Record<Format, Array<[number, number]>> = {');
console.log(fmtTable(buckets, 'work'));
console.log('};');
console.log('');
console.log('export const HYROX_ROXZONE_PERCENTILE_TABLES: Record<Format, Array<[number, number]>> = {');
console.log(fmtTable(buckets, 'roxzone'));
console.log('};');
